local sight = require("cnr.sight")
local config = require("cnr.config")

test("a report of sight counts straight away", function()
  local s = sight.new()
  sight.report(s, 2, true, 10)
  assertEq(sight.sees(s, 2, 10, 1.5), true)
  assertEq(sight.sees(s, 3, 10, 1.5), false)
end)

test("losing sight still counts during the grace period", function()
  local s = sight.new()
  sight.report(s, 2, true, 10)
  sight.report(s, 2, false, 20)
  assertEq(sight.sees(s, 2, 21.4, 1.5), true)
  assertEq(sight.sees(s, 2, 21.5, 1.5), false)
end)

test("a lost report without earlier sight never counts", function()
  local s = sight.new()
  sight.report(s, 2, false, 20)
  assertEq(sight.sees(s, 2, 20, 1.5), false)
end)

test("forget drops a player's sight", function()
  local s = sight.new()
  sight.report(s, 2, true, 10)
  sight.forget(s, 2)
  assertEq(sight.sees(s, 2, 10, 1.5), false)
end)

test("any is true when one of the given players sees", function()
  local s = sight.new()
  sight.report(s, 3, true, 10)
  assertEq(sight.any(s, { 2, 3 }, 10, 1.5), true)
  assertEq(sight.any(s, { 2 }, 10, 1.5), false)
end)

test("the no-route distance follows speed with a minimum", function()
  assertNear(sight.noRouteDistance(27.8, 5, 50), 139, 1e-9)
  assertEq(sight.noRouteDistance(2, 5, 50), 50)
end)

test("config has the sight settings and needs a positive live interval", function()
  local cfg = config.merge(nil)
  assertEq(cfg.sightMaxMeters, 400); assertEq(cfg.sightGraceSeconds, 1.5); assertEq(cfg.sightLiveIntervalSeconds, 1)
  assertEq(cfg.sightNoRouteSeconds, 5); assertEq(cfg.sightNoRouteMinMeters, 50)
  local _, warnings = config.merge({ sightLiveIntervalSeconds = 0 })
  assertEq(#warnings, 1)
end)
