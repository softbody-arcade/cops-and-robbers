local colors = require("cnr.colors")

test("parseHex accepts #rrggbb, rrggbb and #rgb", function()
  local c = colors.parseHex("#ff8000")
  assertNear(c.r, 1, 1e-9); assertNear(c.g, 128/255, 1e-9); assertNear(c.b, 0, 1e-9)
  assertEq(colors.parseHex("FF8000").hex, "#ff8000")
  assertEq(colors.parseHex("#f80").hex, "#ff8800")
end)

test("parseHex rejects garbage", function()
  local c, err = colors.parseHex("#gg0000")
  assertEq(c, nil); assertEq(err, "Use a hex color like #ff0000")
  assertEq((colors.parseHex("")), nil)
  assertEq((colors.parseHex(nil)), nil)
  assertEq((colors.parseHex("#12345")), nil)
end)

test("store set/get/clear by player name", function()
  local s = colors.load(nil)
  colors.set(s, "Reinder", "#ff0000")
  assertEq(colors.get(s, "Reinder").hex, "#ff0000")
  assertEq(colors.get(s, "Bob"), nil)
  colors.clear(s, "Reinder")
  assertEq(colors.get(s, "Reinder"), nil)
end)

test("load ignores invalid entries", function()
  local s = colors.load({ Reinder = "#00ff00", Bob = "nope", [1] = "#000000" })
  assertEq(colors.get(s, "Reinder").hex, "#00ff00")
  assertEq(colors.get(s, "Bob"), nil)
end)
