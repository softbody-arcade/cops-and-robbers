local config = require("cnr.config")

test("merge fills defaults", function()
  local c, w = config.merge(nil)
  assertEq(c.headStartSeconds, 7)
  assertEq(c.runnerCountdownSeconds, 3)
  assertEq(c.resetWaitSeconds, 7)
  assertEq(c.catchHoldSeconds, 7)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.catchMaxSpeedKmh, 3)
  assertEq(c.stillMaxSpeedKmh, 1)
  assertEq(c.copResetMinDistanceMeters, 1000)
  assertEq(c.gasStationRadiusMeters, 25)
  assertEq(c.copSpawnMinMeters, 50)
  assertEq(c.copSpawnMaxMeters, 150)
  assertEq(c.explodeOnCatch, false)
  assertEq(c.includeModVehicles, false)
  assertEq(c.crashSpeedLossKmh, 50)
  assertEq(c.crashPenaltySeconds, 10)
  assertEq(c.roundTimeLimitSeconds, 0)
  assertEq(c.helicopter, true)
  assertEq(c.helicopterArrivalSeconds, 60)
  assertEq(c.helicopterUpSeconds, 120)
  assertEq(c.helicopterRefuelSeconds, 90)
  assertEq(table.concat(c.excludedModels, ","), "citybus,us_semi,md_series,percheron,rockbouncer")
  assertEq(#w, 0)
end)

test("merge keeps valid, rejects invalid, ignores unknown", function()
  local c, w = config.merge({headStartSeconds=10, catchRadiusMeters=-5, explodeOnCatch="yes", bogus=1})
  assertEq(c.headStartSeconds, 10)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.explodeOnCatch, false)
  assertEq(c.bogus, nil)
  assertEq(#w, 3)
end)

test("zero hold or radius rejected, zero headstart allowed", function()
  local c, w = config.merge({catchHoldSeconds=0, catchRadiusMeters=0, headStartSeconds=0})
  assertEq(c.catchHoldSeconds, 7)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.headStartSeconds, 0)
  assertEq(#w, 2)
end)

test("non-finite numbers rejected", function()
  local c, w = config.merge({resetWaitSeconds=math.huge, catchMaxSpeedKmh=0/0})
  assertEq(c.resetWaitSeconds, 7)
  assertEq(c.catchMaxSpeedKmh, 3)
  assertEq(#w, 2)
end)

test("copSpawnMax below min is corrected", function()
  local c, w = config.merge({copSpawnMinMeters=200, copSpawnMaxMeters=100})
  assertEq(c.copSpawnMaxMeters, 200)
  assertEq(#w, 1)
end)

test("weather changes default on, every 3 to 8 minutes", function()
  local c = config.merge({})
  assertEq(c.weatherChanges, true)
  assertEq(c.weatherChangeMinMinutes, 3)
  assertEq(c.weatherChangeMaxMinutes, 8)
end)

test("the minutes are whole and at least 1", function()
  for _, bad in ipairs({ 0, 1.5, -1, "x" }) do
    local c, w = config.merge({ weatherChangeMinMinutes = bad, weatherChangeMaxMinutes = bad })
    assertEq(c.weatherChangeMinMinutes, 3)
    assertEq(c.weatherChangeMaxMinutes, 8)
    assertEq(#w, 2)
  end
end)

test("a max below the min is raised to the min", function()
  local c, w = config.merge({ weatherChangeMinMinutes = 5, weatherChangeMaxMinutes = 2 })
  assertEq(c.weatherChangeMinMinutes, 5)
  assertEq(c.weatherChangeMaxMinutes, 5)
  assertEq(#w, 1)
  assertEq(w[1], "weatherChangeMaxMinutes (2) is below weatherChangeMinMinutes, using 5")
end)

test("setValue compares numbers when the stored max is a string", function()
  local u, err = config.setValue({ weatherChangeMaxMinutes = "8" }, "weatherChangeMinMinutes", "6")
  assertEq(err, nil)
  assertEq(tonumber(u.weatherChangeMaxMinutes), 8)
  assertEq(u.weatherChangeMinMinutes, 6)
end)

test("setValue raises the max with the min, and clamps a lowered max", function()
  local u = config.setValue({ weatherChangeMaxMinutes = 4 }, "weatherChangeMinMinutes", "6")
  assertEq(u.weatherChangeMinMinutes, 6)
  assertEq(u.weatherChangeMaxMinutes, 6)
  u = config.setValue({ weatherChangeMinMinutes = 5 }, "weatherChangeMaxMinutes", "2")
  assertEq(u.weatherChangeMinMinutes, 5)
  assertEq(u.weatherChangeMaxMinutes, 5)
end)

test("setValue min above the default max raises the max, a lowered min leaves it", function()
  local u = config.setValue({}, "weatherChangeMinMinutes", "10")
  assertEq(u.weatherChangeMaxMinutes, 10)
  u = config.setValue({ weatherChangeMinMinutes = 5, weatherChangeMaxMinutes = 8 }, "weatherChangeMinMinutes", "2")
  assertEq(u.weatherChangeMinMinutes, 2); assertEq(u.weatherChangeMaxMinutes, 8)
end)

test("lightning intervals default to 10 to 40 seconds and require positive whole seconds", function()
  local defaults = config.merge({})
  assertEq(defaults.lightningMinSeconds, 10)
  assertEq(defaults.lightningMaxSeconds, 40)
  for _, bad in ipairs({ 0, -2, 1.5, math.huge, "x" }) do
    local c, warnings = config.merge({ lightningMinSeconds = bad, lightningMaxSeconds = bad })
    assertEq(c.lightningMinSeconds, 10)
    assertEq(c.lightningMaxSeconds, 40)
    assertEq(#warnings, 2)
    for _, key in ipairs({ "lightningMinSeconds", "lightningMaxSeconds" }) do
      local updated = config.setValue({}, key, tostring(bad))
      assertEq(updated, nil)
    end
  end
  local c, warnings = config.merge({ lightningMinSeconds = 1, lightningMaxSeconds = 1 })
  assertEq(c.lightningMinSeconds, 1)
  assertEq(c.lightningMaxSeconds, 1)
  assertEq(#warnings, 0)
end)

test("lightning keeps the maximum at least the minimum on load and on single edits", function()
  local c, warnings = config.merge({ lightningMinSeconds = 6, lightningMaxSeconds = 5 })
  assertEq(c.lightningMaxSeconds, 6)
  assertEq(#warnings, 1)
  local updated = assert(config.setValue({}, "lightningMinSeconds", "45"))
  assertEq(updated.lightningMaxSeconds, 45)
  updated = assert(config.setValue(updated, "lightningMinSeconds", "5"))
  assertEq(updated.lightningMinSeconds, 5)
  assertEq(updated.lightningMaxSeconds, 45)
  updated = assert(config.setValue(updated, "lightningMaxSeconds", "3"))
  assertEq(updated.lightningMaxSeconds, 5)
end)

test("defaults table not mutated by merge", function()
  config.merge({headStartSeconds=99})
  assertEq(config.DEFAULTS.headStartSeconds, 7)
end)

test("excludedModels must be a list of strings", function()
  local c, w = config.merge({excludedModels={"citybus", 3}})
  assertEq(c.excludedModels[1], "citybus"); assertEq(#c.excludedModels, 5); assertEq(#w, 1)
  c, w = config.merge({excludedModels={}})
  assertEq(#c.excludedModels, 0); assertEq(#w, 0)
end)

test("setValue parses by setting type", function()
  local raw, err = config.setValue({}, "headStartSeconds", "10")
  assertEq(err, nil); assertEq(raw.headStartSeconds, 10)
  raw = config.setValue(raw, "explodeOnCatch", "true")
  assertEq(raw.explodeOnCatch, true); assertEq(raw.headStartSeconds, 10)
  raw = config.setValue(raw, "excludedModels", "citybus, us_semi")
  assertEq(table.concat(raw.excludedModels, ","), "citybus,us_semi")
end)

test("setValue rejects unknown keys and bad values", function()
  local raw, err = config.setValue({}, "bogus", "1")
  assertEq(raw, nil); assertEq(err, "Unknown setting bogus")
  raw, err = config.setValue({}, "catchRadiusMeters", "-3")
  assertEq(raw, nil); assertEq(err, "Invalid value for catchRadiusMeters: -3")
  raw, err = config.setValue({}, "explodeOnCatch", "maybe")
  assertEq(raw, nil); assertEq(err, "Invalid value for explodeOnCatch: maybe")
end)

