local config = require("cnr.config")

test("merge fills defaults", function()
  local c, w = config.merge(nil)
  assertEq(c.headStartSeconds, 7)
  assertEq(c.runnerCountdownSeconds, 3)
  assertEq(c.resetWaitSeconds, 7)
  assertEq(c.catchHoldSeconds, 7)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.catchMaxSpeedKmh, 3)
  assertEq(c.stillMaxSpeedKmh, 1)
  assertEq(c.copResetMinDistanceMeters, 1000)
  assertEq(c.gasStationRadiusMeters, 25)
  assertEq(c.copSpawnMinMeters, 50)
  assertEq(c.copSpawnMaxMeters, 150)
  assertEq(c.explodeOnCatch, false)
  assertEq(c.includeModVehicles, false)
  assertEq(#w, 0)
end)

test("merge keeps valid, rejects invalid, ignores unknown", function()
  local c, w = config.merge({headStartSeconds=10, catchRadiusMeters=-5, explodeOnCatch="yes", bogus=1})
  assertEq(c.headStartSeconds, 10)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.explodeOnCatch, false)
  assertEq(c.bogus, nil)
  assertEq(#w, 3)
end)

test("zero hold or radius rejected, zero headstart allowed", function()
  local c, w = config.merge({catchHoldSeconds=0, catchRadiusMeters=0, headStartSeconds=0})
  assertEq(c.catchHoldSeconds, 7)
  assertEq(c.catchRadiusMeters, 10)
  assertEq(c.headStartSeconds, 0)
  assertEq(#w, 2)
end)

test("non-finite numbers rejected", function()
  local c, w = config.merge({resetWaitSeconds=math.huge, catchMaxSpeedKmh=0/0})
  assertEq(c.resetWaitSeconds, 7)
  assertEq(c.catchMaxSpeedKmh, 3)
  assertEq(#w, 2)
end)

test("copSpawnMax below min is corrected", function()
  local c, w = config.merge({copSpawnMinMeters=200, copSpawnMaxMeters=100})
  assertEq(c.copSpawnMaxMeters, 200)
  assertEq(#w, 1)
end)

test("defaults table not mutated by merge", function()
  config.merge({headStartSeconds=99})
  assertEq(config.DEFAULTS.headStartSeconds, 7)
end)
