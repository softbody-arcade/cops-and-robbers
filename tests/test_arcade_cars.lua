local cars = require("arcade.cars")
local roster = require("arcade.roster")
local traffic = require("arcade.traffic")

local oldMP = MP
local function setup()
  local sent = {}
  local messages = { send = function(pid, event, payload)
    sent[#sent + 1] = { pid = pid, event = event, payload = payload }
    if pid == 3 then return false, "loading" end
    return true, ""
  end }
  MP = { GetPlayerVehicles = function() return { [0] = "spare" } end }
  local r = roster.new()
  local t = traffic.new(r, messages)
  return cars.new(r, messages, t), sent, r, t
end

test("setup grants one spawn and waits for confirmation before publishing the first car", function()
  local c, sent = setup()
  c:setPublishing(true)
  local ok, reason = c:setup(3, {})
  assertEq(ok, false)
  assertEq(reason, "loading")
  assertEq(c:permitted(3), false)
  assertEq(c:placementPending(3), false)
  c:setup(2, { model = "pickup" })
  assertEq(sent[2].event, "cnr_roundSetup")
  assertEq(sent[2].payload.model, "pickup")
  assertEq(c:permitted(2), true)
  assertEq(c:placementPending(2), true)
  assertEq(c:isPreRound(2, 0), true)
  assertEq(c:claim(2, 8), "permit")
  assertEq(c:permitted(2), false)
  assertEq(c:placementPending(2), true)
  assertEq(c:claim(2, 9), nil)
  assertEq(c:activeVid(2), 8)
  assertEq(c:confirmedVid(2), nil)
  assertEq(#sent, 2)
  assertEq(c:confirm(2, 7), false)
  assertEq(c:placementPending(2), false)
  assertEq(c:isPreRound(2, 0), false)
  c:publish()
  assertEq(sent[3].event, "cnr_roundCars")
  assertEq(table.concat(sent[3].payload.keys, ","), "2-7")
  assertEq(c:confirm(2, 7), false)
  assertEq(c:confirm(2, 0), true)
end)

test("the game controls participation after setup delivery fails", function()
  local c, sent = setup()
  c:setPublishing(true)
  c:setup(3, {})
  c:confirm(3, 0)
  c:publish(5)
  assertEq(table.concat(sent[#sent].payload.keys, ","), "3-0")
  c:removeParticipant(3)
  c:publish(5)
  assertEq(#sent[#sent].payload.keys, 0)
end)

test("a deleted confirmed car gets one replacement and a reroll grants a new permit", function()
  local c, sent = setup()
  c:setPublishing(true)
  c:setup(1, {})
  c:confirm(1, 0)
  assertEq(c:setActive(1, nil), true)
  assertEq(c:vidFor(1), nil)
  assertEq(c:replacementAllowed(1), true)
  assertEq(c:claim(1, 4), "replacement")
  assertEq(c:replacementAllowed(1), false)
  assertEq(c:placementPending(1), true)
  assertEq(table.concat(sent[#sent].payload.keys, ","), "1-4")
  assertEq(c:claim(1, 5), nil)
  c:confirm(1, 4)
  c:setup(1, {})
  assertEq(c:confirmedVid(1), 4)
  assertEq(c:claim(1, 5), "permit")
  assertEq(table.concat(sent[#sent].payload.keys, ","), "1-5")
end)

test("publication skips unchanged broadcasts, sends snapshots, and clears a nonempty list once", function()
  local c, sent = setup()
  c:clearPublished()
  for _, pid in ipairs({ 2, 1 }) do
    c:setup(pid, {})
    c:confirm(pid, 0)
  end
  c:publish()
  c:publish(7)
  assertEq(#sent, 2)
  c:setPublishing(true)
  c:publish()
  c:publish()
  assertEq(#sent, 3)
  assertEq(sent[3].pid, -1)
  assertEq(table.concat(sent[3].payload.keys, ","), "1-0,2-0")
  c:removeParticipant(2)
  c:publish(7)
  c:publish()
  assertEq(sent[4].pid, 7)
  assertEq(sent[5].pid, -1)
  assertEq(table.concat(sent[4].payload.keys, ","), "1-0")
  assertEq(table.concat(sent[5].payload.keys, ","), "1-0")
  c:setPublishing(false)
  c:clearRound()
  assertEq(c:activeVid(1), nil)
  c:clearPublished()
  c:clearPublished()
  assertEq(#sent, 6)
  assertEq(sent[6].pid, -1)
  assertEq(#sent[6].payload.keys, 0)
end)

test("rebuilds track delivered targets and only the matching acknowledgement clears them", function()
  local c, sent, r = setup()
  c:rebuild({ 2 }, { rebuild = 7 }, 7)
  local delivery = c:rebuild({ 1, 2, 3 }, { rebuild = 8 }, 8)
  assertEq(delivery[1], true)
  assertEq(delivery[2], true)
  assertEq(delivery[3], false)
  assertEq(sent[3].pid, 2)
  assertEq(sent[3].event, "cnr_rebuild")
  assertEq(sent[3].payload.rebuild, 8)
  assertEq(c:acknowledgeRebuild(2, 7), false)
  assertEq(c:pendingRebuild(2), true)
  assertEq(c:acknowledgeRebuild(2, 8), true)
  assertEq(c:pendingRebuild(2), false)
  assertEq(c:acknowledgeRebuild(2, 8), false)
  assertEq(c:acknowledgeRebuild(2, nil), false)
  assertEq(c:pendingRebuild(3), false)
  r:leaveLate(1)
  assertEq(c:pendingRebuild(1), false)
end)

test("position sampling requires both vectors while raw position preserves the engine error", function()
  local c = setup()
  MP.GetPositionRaw = function(owner, vid)
    assertEq(owner, 2)
    if vid == 1 then return {}, "unavailable" end
    if vid == 2 then return { pos = { 4, 5, 6 } }, "" end
    return { pos = { 1, 2, 3 }, vel = { x = 4, y = 5, z = 6 } }, ""
  end
  local raw, err = c:rawPosition(2, 1)
  assertEq(raw, nil)
  assertEq(err, "unavailable")
  assertEq(c:position(2, 2), nil)
  assertEq(c:rawPosition(2, 2).pos[3], 6)
  local car = c:position(2, 0)
  assertEq(car.pos.x, 1)
  assertEq(car.vel.z, 6)
end)

MP = oldMP
