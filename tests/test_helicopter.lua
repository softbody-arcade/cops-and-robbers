local helicopter = require("cnr.helicopter")
local config = require("cnr.config")
local function cfg(o) return (config.merge(o)) end
local function std() return cfg({ helicopterArrivalSeconds = 60, helicopterUpSeconds = 120, helicopterRefuelSeconds = 90 }) end

test("the helicopter arrives, flies, refuels and flies again", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.status(h, 10).phase, "arriving"); assertEq(helicopter.status(h, 10).seconds, 60)
  assertEq(helicopter.update(h, 69, false), false)
  assertEq(helicopter.update(h, 70, false), true)
  assertEq(helicopter.status(h, 70).phase, "tracking"); assertEq(helicopter.status(h, 100).seconds, 90)
  assertEq(helicopter.update(h, 190, false), true)
  assertEq(helicopter.status(h, 190).phase, "refuelling"); assertEq(helicopter.status(h, 200).seconds, 80)
  helicopter.update(h, 280, false)
  assertEq(helicopter.status(h, 280).phase, "tracking"); assertEq(helicopter.status(h, 280).seconds, 120)
end)

test("time up keeps counting while searching", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 80, true)
  helicopter.update(h, 150, true)
  assertEq(helicopter.status(h, 150).phase, "searching")
  assertEq(helicopter.status(h, 150).seconds, 40)
  helicopter.update(h, 190, true)
  assertEq(helicopter.status(h, 190).phase, "refuelling")
end)

test("storm, fog and snow ground it for good", function()
  for _, w in ipairs({ "storm", "fog", "snow" }) do
    local h = helicopter.new(std(), w, 10)
    local s = helicopter.status(h, 10)
    assertEq(s.phase, "grounded"); assertEq(s.reason, w); assertEq(s.seconds, nil)
    assertEq(helicopter.update(h, 10000, false), false)
    assertEq(helicopter.flew(h), false)
    assertEq(helicopter.tracking(h), false)
  end
  assertEq(helicopter.flew(helicopter.new(std(), nil, 10)), true)
end)

test("in the open again it finds the runner after 5 s, 10 s in rain", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 80, true)
  assertEq(helicopter.status(h, 80).phase, "searching")
  helicopter.update(h, 81, false)
  helicopter.update(h, 85.9, false)
  assertEq(helicopter.status(h, 85.9).phase, "searching")
  helicopter.update(h, 86, false)
  assertEq(helicopter.status(h, 86).phase, "tracking")
  assertEq(helicopter.tracking(h), true)

  local r = helicopter.new(std(), "rain", 10)
  helicopter.update(r, 70, false)
  helicopter.update(r, 80, true)
  helicopter.update(r, 81, false)
  helicopter.update(r, 90.9, false)
  assertEq(helicopter.status(r, 90.9).phase, "searching")
  helicopter.update(r, 91, false)
  assertEq(helicopter.status(r, 91).phase, "tracking")

  local c = helicopter.new(std(), "clear", 10)
  helicopter.update(c, 70, false)
  helicopter.update(c, 80, true)
  helicopter.update(c, 81, false)
  helicopter.update(c, 83, true)
  helicopter.update(c, 84, false)
  helicopter.update(c, 88, false)
  assertEq(helicopter.status(c, 88).phase, "searching")
  helicopter.update(c, 89, false)
  assertEq(helicopter.status(c, 89).phase, "tracking")
end)

test("an arrival of 0 means it is up on the first update", function()
  local h = helicopter.new(cfg({ helicopterArrivalSeconds = 0 }), "clear", 10)
  helicopter.update(h, 10, false)
  assertEq(helicopter.status(h, 10).phase, "tracking")
end)

test("a refuel of 0 keeps it up with no countdown", function()
  local h = helicopter.new(cfg({ helicopterArrivalSeconds = 0, helicopterRefuelSeconds = 0 }), "clear", 10)
  helicopter.update(h, 10, false)
  assertEq(helicopter.status(h, 10).seconds, nil)
  helicopter.update(h, 10000, false)
  assertEq(helicopter.status(h, 10000).phase, "tracking")
  assertEq(helicopter.status(h, 10000).seconds, nil)
end)

test("a long gap advances through several phases at once", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 280, false)
  assertEq(helicopter.status(h, 280).phase, "tracking")
  assertEq(helicopter.status(h, 280).seconds, 120)
end)

test("going up while the runner is covered starts searching", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, true)
  assertEq(helicopter.status(h, 70).phase, "searching")
  assertEq(helicopter.tracking(h), false)
end)
