local helicopter = require("cnr.helicopter")
local config = require("cnr.config")
local function cfg(o) return (config.merge(o)) end
local function std() return cfg({ helicopterArrivalSeconds = 60, helicopterUpSeconds = 120, helicopterRefuelSeconds = 90 }) end

test("the helicopter arrives, flies, refuels and flies again", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.status(h, 10).phase, "arriving"); assertEq(helicopter.status(h, 10).seconds, 60)
  assertEq(helicopter.update(h, 69, false), false)
  assertEq(helicopter.update(h, 70, false), true)
  assertEq(helicopter.status(h, 70).phase, "tracking"); assertEq(helicopter.status(h, 100).seconds, 90)
  assertEq(helicopter.update(h, 190, false), true)
  assertEq(helicopter.status(h, 190).phase, "refuelling"); assertEq(helicopter.status(h, 200).seconds, 80)
  helicopter.update(h, 280, false)
  assertEq(helicopter.status(h, 280).phase, "tracking"); assertEq(helicopter.status(h, 280).seconds, 120)
end)

test("one update across a whole refuel reports the new flight's seed", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  local first = helicopter.status(h, 70).seed
  h.random = function() return first + 1 end
  assertEq(helicopter.update(h, 280, false), true)
  assertEq(helicopter.status(h, 280).phase, "tracking")
  assertEq(helicopter.status(h, 280).seed, first + 1)
end)

test("time up keeps counting while searching", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 80, true)
  helicopter.update(h, 150, true)
  assertEq(helicopter.status(h, 150).phase, "searching")
  assertEq(helicopter.status(h, 150).seconds, 40)
  helicopter.update(h, 190, true)
  assertEq(helicopter.status(h, 190).phase, "refuelling")
end)

test("a round that starts grounded stays grounded until the weather clears", function()
  for _, w in ipairs({ "storm", "fog", "snow" }) do
    local h = helicopter.new(std(), w, 10)
    local s = helicopter.status(h, 10)
    assertEq(s.phase, "grounded"); assertEq(s.reason, w); assertEq(s.seconds, nil)
    assertEq(helicopter.update(h, 10000, false, false, w), false)
    assertEq(helicopter.flew(h), false)
    assertEq(helicopter.tracking(h), false)
    assertEq(helicopter.update(h, 10100, false, false, nil), true)
    assertEq(helicopter.status(h, 10100).phase, "arriving")
  end
  assertEq(helicopter.new(std(), nil, 10).phase, "arriving")
end)

test("a change to storm, fog or snow grounds it from any phase", function()
  for _, w in ipairs({ "storm", "fog", "snow" }) do
    local h = helicopter.new(std(), "clear", 10)
    assertEq(helicopter.update(h, 20, false, false, w), true, w)
    local s = helicopter.status(h, 20)
    assertEq(s.phase, "grounded", w); assertEq(s.reason, w); assertEq(s.seconds, nil)
    h = helicopter.new(std(), "clear", 10)
    helicopter.update(h, 70, false)
    assertEq(helicopter.update(h, 80, false, false, w), true, w)
    assertEq(helicopter.status(h, 80).phase, "grounded", w)
    assertEq(helicopter.tracking(h), false)
    h = helicopter.new(std(), "clear", 10)
    helicopter.update(h, 70, false)
    helicopter.update(h, 190, false)
    assertEq(helicopter.status(h, 190).phase, "refuelling")
    assertEq(helicopter.update(h, 200, false, false, w), true, w)
    s = helicopter.status(h, 200)
    assertEq(s.phase, "grounded", w); assertEq(s.reason, w); assertEq(s.seconds, nil)
  end
end)

test("guided is off while grounded", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false, true)
  assertEq(helicopter.status(h, 70).guided, true)
  helicopter.update(h, 80, false, true, "storm")
  assertEq(h.guided, false)
  assertEq(helicopter.status(h, 80).guided, nil)
end)

test("it comes back through arriving when the weather clears", function()
  local h = helicopter.new(std(), "storm", 10)
  helicopter.update(h, 100, true, false, "storm")
  assertEq(helicopter.update(h, 200, true, false, nil), true)
  local s = helicopter.status(h, 200)
  assertEq(s.phase, "arriving"); assertEq(s.seconds, 60); assertEq(s.reason, nil)
  assertEq(helicopter.update(h, 260, false, false, nil), true)
  s = helicopter.status(h, 260)
  assertEq(s.phase, "tracking"); assertEq(s.seconds, 120)
end)

test("a zero second arrival goes up at once on clearing", function()
  local h = helicopter.new(cfg({ helicopterArrivalSeconds = 0, helicopterUpSeconds = 120, helicopterRefuelSeconds = 90 }), "fog", 10)
  assertEq(helicopter.update(h, 50, false, false, nil), true)
  assertEq(helicopter.status(h, 50).phase, "tracking")
end)

test("a full time up after each return", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 100, false, false, "snow")
  helicopter.update(h, 150, false, false, nil)
  helicopter.update(h, 210, false, false, nil)
  assertEq(helicopter.status(h, 210).phase, "tracking")
  assertEq(helicopter.status(h, 210).seconds, 120)
  helicopter.update(h, 330, false, false, nil)
  assertEq(helicopter.status(h, 330).phase, "refuelling")
end)

test("a grounding during a refuel cancels it", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 190, false)
  helicopter.update(h, 200, false, false, "storm")
  assertEq(h.phaseEnd, nil)
  assertEq(helicopter.update(h, 400, false, false, "storm"), false)
  assertEq(helicopter.status(h, 400).phase, "grounded")
end)

test("a new grounding reason is reported", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.update(h, 20, false, false, "storm"), true)
  assertEq(helicopter.update(h, 21, false, false, "storm"), false)
  assertEq(helicopter.update(h, 30, false, false, "snow"), true)
  assertEq(helicopter.status(h, 30).reason, "snow")
end)

test("flew is true once it has been up", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.flew(h), false)
  helicopter.update(h, 70, false)
  assertEq(helicopter.flew(h), true)
  helicopter.update(h, 80, false, false, "storm")
  assertEq(helicopter.flew(h), true)
  assertEq(helicopter.flew(helicopter.new(std(), "storm", 10)), false)
end)

test("back in the open it tracks again at once, also in rain", function()
  for _, w in ipairs({ "clear", "rain" }) do
    local h = helicopter.new(std(), w, 10)
    helicopter.update(h, 70, false)
    helicopter.update(h, 80, true)
    assertEq(helicopter.update(h, 82, true), true, w)
    assertEq(helicopter.status(h, 82).phase, "searching", w)
    assertEq(helicopter.update(h, 82.25, true), false)
    assertEq(helicopter.update(h, 82.5, false), true, w)
    assertEq(helicopter.status(h, 82.5).phase, "tracking", w)
    assertEq(helicopter.tracking(h), true)
    assertEq(helicopter.status(h, 82.5).seconds, 107.5)
  end
end)

test("it loses the runner only after 2 s of cover in a row", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  assertEq(helicopter.update(h, 80, true), false)
  assertEq(helicopter.update(h, 81.9, true), false)
  assertEq(helicopter.status(h, 81.9).phase, "tracking")
  assertEq(helicopter.tracking(h), true)
  assertEq(helicopter.update(h, 82, true), true)
  assertEq(helicopter.status(h, 82).phase, "searching")
end)

test("a short cover such as a bridge keeps it tracking and restarts the 2 s", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 70, false)
  helicopter.update(h, 80, true)
  assertEq(helicopter.update(h, 81.5, false), false)
  assertEq(helicopter.update(h, 81.75, true), false)
  assertEq(helicopter.update(h, 83.5, true), false)
  assertEq(helicopter.status(h, 83.5).phase, "tracking")
  assertEq(helicopter.update(h, 83.75, true), true)
  assertEq(helicopter.status(h, 83.75).phase, "searching")
  assertEq(helicopter.LOSE_SECONDS, 2)
end)

test("an arrival of 0 means it is up on the first update", function()
  local h = helicopter.new(cfg({ helicopterArrivalSeconds = 0 }), "clear", 10)
  helicopter.update(h, 10, false)
  assertEq(helicopter.status(h, 10).phase, "tracking")
end)

test("a refuel of 0 keeps it up with no countdown", function()
  local h = helicopter.new(cfg({ helicopterArrivalSeconds = 0, helicopterRefuelSeconds = 0 }), "clear", 10)
  helicopter.update(h, 10, false)
  assertEq(helicopter.status(h, 10).seconds, nil)
  helicopter.update(h, 10000, false)
  assertEq(helicopter.status(h, 10000).phase, "tracking")
  assertEq(helicopter.status(h, 10000).seconds, nil)
end)

test("a long gap advances through several phases at once", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 280, false)
  assertEq(helicopter.status(h, 280).phase, "tracking")
  assertEq(helicopter.status(h, 280).seconds, 120)
end)

test("going up while the runner is covered starts searching at once", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.update(h, 70, true), true)
  assertEq(helicopter.status(h, 70).phase, "searching")
  assertEq(helicopter.tracking(h), false)
  helicopter.update(h, 75, false)
  helicopter.update(h, 190, false)
  assertEq(helicopter.status(h, 190).phase, "refuelling")
  helicopter.update(h, 279, true)
  assertEq(helicopter.update(h, 280, true), true)
  assertEq(helicopter.status(h, 280).phase, "searching")
end)

test("each flight gets its own seed, sent only while up", function()
  local picks = { 11, 22 }
  local n = 0
  local function random() n = n + 1; return picks[n] end
  local h = helicopter.new(std(), "clear", 10, random)
  assertEq(helicopter.status(h, 10).seed, nil)
  helicopter.update(h, 70, false)
  assertEq(helicopter.status(h, 70).seed, 11)
  helicopter.update(h, 190, false)
  assertEq(helicopter.status(h, 190).seed, nil)
  helicopter.update(h, 280, false)
  assertEq(helicopter.status(h, 280).seed, 22)
  helicopter.update(h, 281, true)
  helicopter.update(h, 284, true)
  assertEq(helicopter.status(h, 284).phase, "searching")
  assertEq(helicopter.status(h, 284).seed, 22)
  helicopter.update(h, 285, false)
  assertEq(helicopter.status(h, 285).seed, 22)
  local d = helicopter.new(std(), "clear", 10)
  helicopter.update(d, 70, false)
  local s = helicopter.status(d, 70).seed
  assertEq(math.type(s), "integer")
  assertEq(s >= 1 and s <= 2147483646, true)
end)

test("guided is in the status only while up", function()
  local h = helicopter.new(std(), "clear", 10)
  helicopter.update(h, 60, true, true)
  assertEq(helicopter.status(h, 60).guided, nil)
  helicopter.update(h, 70, true, true)
  assertEq(helicopter.status(h, 70).phase, "searching")
  assertEq(helicopter.status(h, 70).guided, true)
  helicopter.update(h, 71, true, false)
  assertEq(helicopter.status(h, 71).guided, nil)
  helicopter.update(h, 190, true, true)
  assertEq(helicopter.status(h, 190).phase, "refuelling")
  assertEq(helicopter.status(h, 190).guided, nil)
end)

test("a change of guided is reported while up, and only then", function()
  local h = helicopter.new(std(), "clear", 10)
  assertEq(helicopter.update(h, 70, true, false), true)
  assertEq(helicopter.update(h, 71, true, true), true)
  assertEq(helicopter.update(h, 72, true, true), false)
  assertEq(helicopter.update(h, 73, true, false), true)
  assertEq(helicopter.update(h, 190, true, false), true)
  assertEq(helicopter.update(h, 191, true, true), false)
end)
