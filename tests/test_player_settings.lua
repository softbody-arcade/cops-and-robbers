local ps = require("copsAndRobbers/playerSettings")
test("a missing or broken settings file means headlights on and siren off", function()
  for _, bad in ipairs({ "x", 3, { headlights = "yes", siren = 1 }, { 1, 2 } }) do
    local p = ps.load(bad)
    assertEq(p.headlights, true); assertEq(p.siren, false)
  end
  local n = ps.load(nil)
  assertEq(n.headlights, true); assertEq(n.siren, false)
  local p = ps.load({ headlights = false, siren = true, extra = true })
  assertEq(p.headlights, false); assertEq(p.siren, true); assertEq(p.extra, nil)
  local only = ps.load({ siren = true })
  assertEq(only.headlights, true); assertEq(only.siren, true)
end)
test("set takes only known keys and booleans", function()
  local p = ps.load(nil)
  assertEq(ps.set(p, "headlights", false), true); assertEq(p.headlights, false)
  assertEq(ps.set(p, "headlights", false), false)
  assertEq(ps.set(p, "siren", "on"), false); assertEq(p.siren, false)
  assertEq(ps.set(p, "color", true), false); assertEq(p.color, nil)
end)
