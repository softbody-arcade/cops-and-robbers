local ps = require("copsAndRobbers/playerSettings")
test("a missing or broken settings file means headlights on and siren off", function()
  for _, bad in ipairs({ "x", 3, { headlights = "yes", siren = 1 }, { 1, 2 } }) do
    local p = ps.load(bad)
    assertEq(p.headlights, true); assertEq(p.siren, false)
  end
  local n = ps.load(nil)
  assertEq(n.headlights, true); assertEq(n.siren, false)
  local p = ps.load({ headlights = false, siren = true, extra = true })
  assertEq(p.headlights, false); assertEq(p.siren, true); assertEq(p.extra, nil)
  local only = ps.load({ siren = true })
  assertEq(only.headlights, true); assertEq(only.siren, true)
end)
test("set takes only known keys and booleans", function()
  local p = ps.load(nil)
  assertEq(ps.set(p, "headlights", false), true); assertEq(p.headlights, false)
  assertEq(ps.set(p, "headlights", false), false)
  assertEq(ps.set(p, "siren", "on"), false); assertEq(p.siren, false)
  assertEq(ps.set(p, "color", true), false); assertEq(p.color, nil)
end)
test("route loads as out of sight when missing or unknown", function()
  assertEq(ps.load(nil).route, "sight")
  assertEq(ps.load({ route = 5 }).route, "sight")
  assertEq(ps.load({ route = "fast" }).route, "sight")
  assertEq(ps.load({ route = "never" }).route, "never")
end)
test("route takes only its three values", function()
  local p = ps.load(nil)
  assertEq(ps.set(p, "route", "always"), true); assertEq(p.route, "always")
  assertEq(ps.set(p, "route", "always"), false)
  assertEq(ps.set(p, "route", true), false)
  assertEq(ps.set(p, "route", "fast"), false)
  assertEq(ps.set(p, "headlights", "never"), false)
end)
test("the searchlight beam is on by default and loads and sets as a boolean", function()
  assertEq(ps.load(nil).beam, true)
  assertEq(ps.load({ beam = false }).beam, false)
  assertEq(ps.load({ beam = "no" }).beam, true)
  local p = ps.load(nil)
  assertEq(ps.set(p, "beam", false), true); assertEq(p.beam, false)
  assertEq(ps.set(p, "beam", "no"), false); assertEq(p.beam, false)
end)
test("the helicopter sound is on by default and loads and sets as a boolean", function()
  assertEq(ps.load(nil).sound, true)
  assertEq(ps.load({ sound = false }).sound, false)
  assertEq(ps.load({ sound = "no" }).sound, true)
  local p = ps.load(nil)
  assertEq(ps.set(p, "sound", false), true); assertEq(p.sound, false)
  assertEq(ps.set(p, "sound", false), false)
  assertEq(ps.set(p, "sound", "no"), false); assertEq(p.sound, false)
  assertEq(ps.set(p, "sound", true), true); assertEq(p.sound, true)
end)
test("the helicopter model is on by default and loads and sets as a boolean", function()
