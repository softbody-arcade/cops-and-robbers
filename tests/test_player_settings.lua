test("the HUD is shown by default and hudHidden loads and sets as a boolean", function()
  assertEq(ps.load(nil).hudHidden, false)
  assertEq(ps.load({ hudHidden = true }).hudHidden, true)
  assertEq(ps.load({ hudHidden = "yes" }).hudHidden, false)
  assertEq(ps.load({ hudHidden = 1 }).hudHidden, false)
  local p = ps.load(nil)
  assertEq(ps.set(p, "hudHidden", true), true); assertEq(p.hudHidden, true)
  assertEq(ps.set(p, "hudHidden", true), false)
  assertEq(ps.set(p, "hudHidden", "no"), false); assertEq(p.hudHidden, true)
end)
